// ─── Helpers ─────────────────────────────────────────────────────────────────

function readText(p: string): string {
  try { return fs.readFileSync(p, "utf-8"); }
  catch { return ""; }
}

function readJson<T>(p: string): T | null {
  try { return JSON.parse(fs.readFileSync(p, "utf-8")) as T; }
  catch { return null; }
}

function ensureDir(d: string) {
  if (!fs.existsSync(d)) fs.mkdirSync(d, { recursive: true });
}

function ts() { return new Date().toISOString(); }

// ─── Mind Loader ─────────────────────────────────────────────────────────────

interface MindContext {
  name:      string;
  thinking:  string;
  framework: string;
  phrases:   string;
}

function loadMind(mindId: string, displayName: string): MindContext {
  const base = path.join(MINDS_DIR, mindId);
  return {
    name:      displayName,
    thinking:  readText(path.join(base, "sources",   "thinking_dna.yaml")).slice(0, 1200),
    framework: readText(path.join(base, "artifacts", "framework-primary.md")).slice(0, 1500),
    phrases:   readText(path.join(base, "artifacts", "signature-phrases.md")).slice(0, 600),
  };
}

