// ─── Claude Session ───────────────────────────────────────────────────────────

let _session: ReturnType<typeof createAgentSession> extends Promise<infer T> ? T : never | null = null as any;

async function getSession() {
  if (_session) return _session;
  const authStorage    = AuthStorage.create();
  const modelRegistry  = new ModelRegistry(authStorage);
  const result = await createAgentSession({
    sessionManager: SessionManager.inMemory(),
    authStorage,
    modelRegistry,
  });
  _session = result;
  return result;
}

async function callClaude(prompt: string): Promise<string> {
  const { session } = await getSession();
  const chunks: string[] = [];

  const unsubscribe = session.subscribe((event: any) => {
    if (
      event.type === "message_update" &&
      event.assistantMessageEvent?.type === "text_delta"
    ) {
      const delta = event.assistantMessageEvent.delta as string;
      process.stdout.write(delta);
      chunks.push(delta);
    }
  });

  try {
    await session.prompt(prompt);
  } finally {
    unsubscribe();
  }

  return chunks.join("");
}

// ─── JSON Extractor ───────────────────────────────────────────────────────────

function extractJson(text: string): string | null {
  // Primary: custom markers
  const marked = text.match(/<<JSON_START>>([\s\S]*?)<<JSON_END>>/);
  if (marked) return marked[1].trim();

  // Fallback 1: markdown code block
  const md = text.match(/```(?:json)?\s*([\s\S]*?)```/);
  if (md) return md[1].trim();

  // Fallback 2: raw JSON object (first { ... })
  const raw = text.match(/\{[\s\S]*\}/);
  if (raw) return raw[0];

  return null;
}

// ─── Fallback Approval (if Claude fails) ─────────────────────────────────────

function buildFallbackApproval(input: any): any {
  console.log("\n  ⚠️  Usando aprovação fallback (sem chamada Claude)...");
  return {
    version:       "1.0",
    project:       PROJECT_ID,
    reviewed_at:   ts(),
    status:        "approved",
    strategy_board: {
      ray_dalio:        { vote: "approve", framework_applied: "Principles-Based Decision Making", rationale: "Fallback auto-approval: principle 'move fast on clear bottlenecks' applies.", amendments: [] },
      eliyahu_goldratt: { vote: "approve", framework_applied: "Theory of Constraints",           rationale: "Fallback: constraint identified by flow-intelligence is the system bottleneck — attack it first.", amendments: [] },
      michael_porter:   { vote: "approve", framework_applied: "Five Forces / Value Chain",        rationale: "Fallback: operational efficiency improvement aligns with value chain optimization.", amendments: [] },
    },
    consensus:           "approved",
    board_synthesis:     "Auto-approved: all actions address identified bottlenecks directly.",
    critical_constraint: input.summary?.top_bottleneck || "unknown",
    actions: (input.actions || []).map((a: any) => ({
      ...a,
      status: "approved",
      amendment_reason: null,
    })),
  };
}

// ─── Main ─────────────────────────────────────────────────────────────────────

async function main() {
  console.log("╔══════════════════════════════════════════════════╗");
  console.log("║   Department of Strategy — Review & Approval     ║");
  console.log("║   Minds: Dalio · Goldratt · Porter               ║");
  console.log("╚══════════════════════════════════════════════════╝");
  console.log(`\n🎯 Projeto: ${PROJECT_ID}`);

  // 1. Ler growth-actions.json
  const actionsPath = path.join(FLOW_DIR, "growth-actions.json");
  if (!fs.existsSync(actionsPath)) {
    console.error(`\n❌ growth-actions.json não encontrado em: ${actionsPath}`);
    console.error("   Execute primeiro: npx tsx scripts/flow-intelligence.ts");
    process.exit(1);
  }

  const inputJson = readJson<any>(actionsPath);
  if (!inputJson) {
    console.error("❌ Erro ao parsear growth-actions.json");
    process.exit(1);
  }

  console.log(`\n  ✓ growth-actions.json carregado`);
  console.log(`  ✓ ${inputJson.actions?.length || 0} ações para revisar`);
  console.log(`  ✓ Top bottleneck: ${inputJson.summary?.top_bottleneck || "N/A"} (ICE: ${inputJson.summary?.top_ice_score || 0})`);

  // 2. Carregar Minds
  console.log("\n📚 [Strategy] Carregando minds do board estratégico...");
  const minds: MindContext[] = [
    loadMind("ray_dalio",        "Ray Dalio"),
    loadMind("eliyahu_goldratt", "Eliyahu Goldratt"),
    loadMind("michael_porter",   "Michael Porter"),
  ];
  minds.forEach((m) => console.log(`  ✓ ${m.name} — framework carregado`));

  // 3. Construir prompt
  const prompt = buildReviewPrompt(minds, JSON.stringify(inputJson, null, 2));
  console.log(`\n  ✓ Prompt construído (${prompt.length} chars)`);

  // 4. Chamar Claude
  let approved: any;
  console.log("\n🤖 [Strategy Board] Revisando plano de ação...\n");
  console.log("─".repeat(60));

  try {
    const rawResponse = await callClaude(prompt);
    console.log("\n" + "─".repeat(60));

    const jsonStr = extractJson(rawResponse);
    if (!jsonStr) throw new Error("Não foi possível extrair JSON da resposta");

    approved = JSON.parse(jsonStr);
    console.log("\n  ✅ Resposta do board parseada com sucesso");
  } catch (err) {
    console.error(`\n  ⚠️  Erro ao processar resposta Claude: ${err}`);
    approved = buildFallbackApproval(inputJson);
  }

  // 5. Escrever approved-actions.json
  ensureDir(FLOW_DIR);
  const approvedPath = path.join(FLOW_DIR, "approved-actions.json");
  fs.writeFileSync(approvedPath, JSON.stringify(approved, null, 2), "utf-8");

  // 6. Sumário
  const approvedCount  = (approved.actions || []).filter((a: any) => a.status === "approved"  || a.status === "amended").length;
  const rejectedCount  = (approved.actions || []).filter((a: any) => a.status === "rejected").length;
  const amendedCount   = (approved.actions || []).filter((a: any) => a.status === "amended").length;

  console.log("\n╔══════════════════════════════════════════════════╗");
  console.log("║   ✅ Strategy Review — Concluído                  ║");
  console.log("╚══════════════════════════════════════════════════╝");
  console.log(`\n  Consensus:     ${approved.consensus?.toUpperCase() || "N/A"}`);
  console.log(`  Aprovadas:     ${approvedCount}`);
  console.log(`  Emendadas:     ${amendedCount}`);
  console.log(`  Rejeitadas:    ${rejectedCount}`);
  console.log(`  Constraint #1: ${approved.critical_constraint || "N/A"}`);
  console.log(`\n  📋 approved-actions.json → ${approvedPath}\n`);

  if (approved.consensus === "rejected") {
    console.error("🚫 Plano rejeitado pelo board de estratégia. Revise o bottleneck-report.md.");
    process.exit(1);
  }
}

main().catch((e) => {
  console.error("❌ Erro no Department of Strategy:", e);
  process.exit(1);
});
